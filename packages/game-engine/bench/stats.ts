/** Wilson score interval (95% by default) for a binomial proportion k / n. */
export function wilson(k: number, n: number, z = 1.96): { p: number; lo: number; hi: number } {
  if (n === 0) return { p: 0, lo: 0, hi: 1 };
  const p = k / n;
  const z2 = z * z;
  const denom = 1 + z2 / n;
  const center = (p + z2 / (2 * n)) / denom;
  const half = (z * Math.sqrt((p * (1 - p)) / n + z2 / (4 * n * n))) / denom;
  return { p, lo: Math.max(0, center - half), hi: Math.min(1, center + half) };
}

export const pct = (x: number): string => `${(100 * x).toFixed(1)}%`;

export function formatCi(k: number, n: number): string {
  const { p, lo, hi } = wilson(k, n);
  return `${pct(p).padStart(6)} [${pct(lo)}, ${pct(hi)}]`;
}

export function median(xs: readonly number[]): number {
  const s = [...xs].sort((a, b) => a - b);
  if (s.length === 0) return 0;
  const m = Math.floor(s.length / 2);
  return s.length % 2 ? s[m]! : (s[m - 1]! + s[m]!) / 2;
}
