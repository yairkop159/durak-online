/**
 * The PWA files, generated in code (a local Vite plugin): the web app manifest, the icons
 * (icons.ts), an offline page and a small service worker. Served by the dev server and emitted at
 * the root of `dist` by `vite build` (the production server serves dist's root files as they are).
 *
 * The service worker only answers navigations: network first, the offline page when the network
 * is gone. Assets, /socket.io and /health are never intercepted, so a deploy is never masked by a
 * stale cache and the game always talks to the live server. No offline play.
 */
import { createHash } from 'node:crypto';
import type { Plugin } from 'vite';
import { ICON_FILES, iconPng } from './icons';
import { THEME_FILE, readThemeColors, type ThemeColors } from './theme';

export const APP_NAME = 'דוראק אונליין';
export const APP_SHORT_NAME = 'דוראק';

export interface PwaFile {
  /** Path relative to the site root (no leading slash). */
  readonly path: string;
  readonly contentType: string;
  readonly body: string | Buffer;
}

export function manifest(theme: ThemeColors): Record<string, unknown> {
  return {
    id: '/',
    name: APP_NAME,
    short_name: APP_SHORT_NAME,
    description: 'משחק הקלפים דוראק: עם חברים או נגד המחשב',
    lang: 'he',
    dir: 'rtl',
    start_url: '/',
    scope: '/',
    display: 'standalone',
    orientation: 'any',
    background_color: theme.bg0,
    theme_color: theme.bg0,
    icons: ICON_FILES.filter((f) => f.purpose === 'any' || f.purpose === 'maskable').map((f) => ({
      src: `/${f.path}`,
      sizes: `${f.size}x${f.size}`,
      type: 'image/png',
      purpose: f.purpose,
    })),
  };
}

