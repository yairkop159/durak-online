/** The service worker's source. `version` names its cache; `precache` = root-relative URLs. */
export function serviceWorkerSource(version: string, precache: readonly string[]): string {
  return `/* Durak Online service worker (generated by build/pwa.ts). Navigations only: offline page fallback. */
const CACHE = ${JSON.stringify(`durak-shell-${version}`)};
const PRECACHE = ${JSON.stringify(precache)};
const OFFLINE = '/offline.html';

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('durak-shell-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.mode !== 'navigate' || request.method !== 'GET') return;
  event.respondWith(
    fetch(request).catch(() =>
      caches.match(OFFLINE).then(
        (cached) => cached || new Response('Offline', { status: 503, headers: { 'Content-Type': 'text/plain; charset=utf-8' } }),
      ),
    ),
  );
});
`;
}

/** Every generated file, from the theme colors. */
export function pwaFiles(theme: ThemeColors): PwaFile[] {
  const icons: PwaFile[] = ICON_FILES.map((f) => ({ path: f.path, contentType: 'image/png', body: iconPng(f, theme) }));
  const offline: PwaFile = { path: 'offline.html', contentType: 'text/html; charset=utf-8', body: offlineHtml(theme) };
  const man: PwaFile = {
    path: 'manifest.webmanifest',
    contentType: 'application/manifest+json',
    body: `${JSON.stringify(manifest(theme), null, 2)}\n`,
  };
  // The cache is renamed whenever anything it holds changes.
  const precached = [offline, ...icons];
  const hash = createHash('sha256');
  for (const f of precached) hash.update(f.path).update(f.body);
  const version = hash.digest('hex').slice(0, 12);
  const sw: PwaFile = {
    path: 'sw.js',
    contentType: 'text/javascript; charset=utf-8',
    body: serviceWorkerSource(version, precached.map((f) => `/${f.path}`)),
  };
  return [man, offline, sw, ...icons];
}

export function pwaPlugin(): Plugin {
  let files: Map<string, PwaFile> | null = null;
  const get = () => (files ??= new Map(pwaFiles(readThemeColors()).map((f) => [`/${f.path}`, f])));
  return {
    name: 'durak-pwa',
    configureServer(server) {
      server.watcher.add(THEME_FILE);
      server.watcher.on('change', (file) => {
        if (file.replace(/\\/g, '/') === THEME_FILE.replace(/\\/g, '/')) files = null;
      });
      server.middlewares.use((req, res, next) => {
        const file = req.url ? get().get(req.url.split('?')[0]!) : undefined;
        if (!file || (req.method !== 'GET' && req.method !== 'HEAD')) return next();
        res.setHeader('Content-Type', file.contentType);
        res.setHeader('Cache-Control', 'no-cache');
        res.end(req.method === 'HEAD' ? undefined : file.body);
      });
    },
    generateBundle() {
      for (const f of get().values()) this.emitFile({ type: 'asset', fileName: f.path, source: f.body });
    },
  };
}
